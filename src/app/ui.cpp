std::vector<u8> buildFontAtlas(int& w, int& h) {
    w = FONT_GLYPHS * FONT_CELL_W; h = FONT_CELL_H;
    std::vector<u8> px((size_t)w * h * 4, 0);
    for (int g = 0; g < FONT_GLYPHS; g++)
        for (int r = 0; r < 7; r++) for (int c = 0; c < 5; c++)
            if (FONT_5X7[g][r] & (0x10 >> c)) {
                u8* p = &px[((size_t)r * w + g * FONT_CELL_W + c) * 4];
                p[0] = p[1] = p[2] = p[3] = 255;
            }
    return px;
}

void Ui::quad(const float p[4][2], const float uv[4][2], float layer, float mode, u32 color) {
    static const int tri[6] = {0, 1, 2, 0, 2, 3};
    for (int k : tri) verts.push_back({p[k][0], p[k][1], uv[k][0], uv[k][1], layer, mode, color});
}

void Ui::rect(float x, float y, float w, float h, u32 color) {
    float s = scale;
    const float p[4][2] = {{x * s, y * s}, {(x + w) * s, y * s}, {(x + w) * s, (y + h) * s}, {x * s, (y + h) * s}};
    const float uv[4][2] = {};
    quad(p, uv, 0, 0, color);
}

void Ui::frame(float x, float y, float w, float h, float t, u32 c) {
    rect(x, y, w, t, c); rect(x, y + h - t, w, t, c); rect(x, y + t, t, h - 2 * t, c); rect(x + w - t, y + t, t, h - 2 * t, c);
}

float Ui::text(float x, float y, std::string_view str, u32 color, bool shadow) {
    if (shadow) { u32 sc = (color & 0xFF000000u) | ((color & 0xFCFCFC) >> 2); text(x + 1, y + 1, str, sc, false); }
    const float aw = (float)(FONT_GLYPHS * FONT_CELL_W), s = scale;
    float cx = x;
    for (char ch : str) {
        int g = (unsigned char)ch - 32;
        if (g < 0 || g >= FONT_GLYPHS) g = '?' - 32;
        if (g != 0) {
            float u0 = (float)(g * FONT_CELL_W) / aw, u1 = (float)(g * FONT_CELL_W + 5) / aw;
            const float p[4][2] = {{cx * s, y * s}, {(cx + 5) * s, y * s}, {(cx + 5) * s, (y + 7) * s}, {cx * s, (y + 7) * s}};
            const float uv[4][2] = {{u0, 0}, {u1, 0}, {u1, 7.0f / FONT_CELL_H}, {u0, 7.0f / FONT_CELL_H}};
            quad(p, uv, 0, 1, color);
        }
        cx += FONT_CELL_W;
    }
    return cx - x;
}

void Ui::sprite(float x, float y, float w, float h, int layer, u32 tint) {
    float s = scale;
    const float p[4][2] = {{x * s, y * s}, {(x + w) * s, y * s}, {(x + w) * s, (y + h) * s}, {x * s, (y + h) * s}};
    const float uv[4][2] = {{0, 0}, {1, 0}, {1, 1}, {0, 1}};
    quad(p, uv, (float)layer, 2, tint);
}

void Ui::bitmap(float x, float y, const u16* rows, int w, int h, u32 color) {
    for (int r = 0; r < h; r++)
        for (int c = 0; c < w; ) {
            if (!(rows[r] & (0x8000 >> c))) { c++; continue; }
            int run = 1; while (c + run < w && (rows[r] & (0x8000 >> (c + run)))) run++;   // merge horizontal runs
            rect(x + c, y + r, (float)run, 1, color); c += run;
        }
}

void Ui::blockIcon(float cx, float cy, float size, BlockState b, const BlockRegistry& reg, const BlockTextures& tex) {
    const BlockDef& d = reg.def(b);
    float s = scale, r = size * 0.5f * s, X = cx * s, Y = cy * s;
    if (d.shape != BlockShape::Cube) {   // flat sprite for plants, torches, wires...
        const float p[4][2] = {{X - r, Y - r}, {X + r, Y - r}, {X + r, Y + r}, {X - r, Y + r}};
        const float uv[4][2] = {{0, 0}, {1, 0}, {1, 1}, {0, 1}};
        u32 tint = d.tint == Tint::None ? rgba(255, 255, 255) : rgba(110, 170, 70);
        quad(p, uv, tex.face(b, FACE_NZ), 2, tint);
        return;
    }
    float hw = r * 0.87f, q = r * 0.5f;
    u32 top = d.tint != Tint::None ? rgba(120, 180, 80) : rgba(255, 255, 255);
    // top rhombus
    const float pt[4][2] = {{X, Y - r}, {X + hw, Y - q}, {X, Y}, {X - hw, Y - q}};
    const float uv[4][2] = {{0, 0}, {1, 0}, {1, 1}, {0, 1}};
    quad(pt, uv, tex.face(b, FACE_PY), 2, top);
    const float pl[4][2] = {{X - hw, Y - q}, {X, Y}, {X, Y + r}, {X - hw, Y + q}};
    u32 side = d.tint == Tint::Foliage ? rgba(90, 140, 60) : rgba(200, 200, 200);
    quad(pl, uv, tex.face(b, FACE_NZ), 2, side);
    const float pr[4][2] = {{X, Y}, {X + hw, Y - q}, {X + hw, Y + q}, {X, Y + r}};
    u32 side2 = d.tint == Tint::Foliage ? rgba(70, 110, 50) : rgba(150, 150, 150);
    quad(pr, uv, tex.face(b, FACE_PX), 2, side2);
}

